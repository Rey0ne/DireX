interface SpatialMatch {
  name: string;
  type: 'interior-designer' | 'architect';
  country: string;
  signature: string;
  materials: string;
  colors: string;
  spatialFeatures: string;
  score: number;
}

/** Fast keyword search across all interior designers and architects */
export function searchSpatialKB(query: string): string {
  const tokens = query.toLowerCase().split(/[\s,，、/\-—|]+/).filter(t => t.length >= 2);
  if (!tokens.length) return '';

  const matches: SpatialMatch[] = [];

  // Parse INTERIOR_DESIGNERS_DB — extract table rows
  const interiorSection = INTERIOR_DESIGNERS_DB;
  // Match table rows: | Name | signature | materials | colors | features |
  const rowRe = /\|\s*(.+?)\s*\|(.+?)\|(.+?)\|(.+?)\|(.+?)\|/g;
  let currentCountry = '';
  let currentType: 'interior-designer' | 'architect' = 'interior-designer';

  // Split by country/section headers
  const lines = interiorSection.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    // Detect section
    if (line.includes('### ') && !line.includes('|')) {
      currentCountry = line.replace(/^###\s*/, '').trim();
      // Check if we're in architect section
      if (line.includes('建筑大师') || line.includes('Architecture Masters')) {
        currentType = 'architect';
      } else {
        currentType = 'interior-designer';
      }
      continue;
    }

    // Parse table row
    const rowMatch = line.match(rowRe);
    if (!rowMatch) continue;

    const name = rowMatch[1]?.trim();
    const signature = rowMatch[2]?.trim() || '';
    const materials = rowMatch[3]?.trim() || '';
    const colors = rowMatch[4]?.trim() || '';
    const spatialFeatures = rowMatch[5]?.trim() || '';

    if (!name || name === '设计师/事务所' || name === '建筑师' || name.includes('---')) continue;
    if (name.includes('代际') || name.includes('视觉签名')) continue;

    const haystack = `${name} ${signature} ${materials} ${colors} ${spatialFeatures} ${currentCountry}`.toLowerCase();
    let score = 0;
    for (const t of tokens) {
      if (haystack.includes(t)) score += t.length >= 4 ? 3 : 2;
      for (let j = 0; j <= t.length - 2; j++) {
        if (haystack.includes(t.substring(j, j + 2))) score += 0.5;
      }
    }

    if (score > 0) {
      matches.push({ name, type: currentType, country: currentCountry, signature, materials, colors, spatialFeatures, score });
    }
  }

  matches.sort((a, b) => b.score - a.score);
  const unique = matches.filter((m, i, arr) => arr.findIndex(x => x.name === m.name) === i);

  const blocks = unique.slice(0, 6).map(m => {
    const typeTag = m.type === 'architect' ? '建筑师' : '室内设计师';
    return `### ${m.name} (${typeTag} / ${m.country})\n**视觉签名**: ${m.signature}\n**材质**: ${m.materials}\n**配色**: ${m.colors}\n**空间特征**: ${m.spatialFeatures}`;
  });

  return blocks.join('\n\n---\n\n');
}

